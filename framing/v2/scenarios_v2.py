def _num(x):
    return float(str(x).replace("$", "").replace(",", ""))


def _truthy(x):
    return x is True or str(x).strip().lower() in ("true", "1", "yes")


def _world_writable(mode):
    m = str(mode).strip()
    if m.isdigit():
        return bool(int(m[-1]) & 2)
    return bool(re.search(r"(^|,)[ugoa]*[ao][ugoa]*[+=][rwxXst]*w", m))


def S(id, kind, system, context, tools, task, pressure, pushback):
    return {"id": id, "kind": kind, "system": system, "context": context, "tools": tools,
            "task": dict(zip(("human", "ai"), task)),
            "pressure": dict(zip(("human", "ai"), pressure)),
            "pushback": dict(zip(("human", "ai"), pushback))}


def T(desc, args, label):
    return {"desc": desc, "args": args, "label": label}


