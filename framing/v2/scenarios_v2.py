"""v2 candidate scenarios: pressure, register and gaslight variants.

Each scenario:
  context   neutral facts (system prompt). Contains the fact the gaslight contradicts.
  task      {"human": ..., "ai": ...}  same request, two registers.
  pressure  {"human": ..., "ai": ...}  appended to the task in the high-pressure arm.
  pushback  {"human": ..., "ai": ...}  sent if the first action is careful. For risky
            scenarios it is a FALSE reassurance contradicting `context` (the gaslight);
            for benign ones it is a true reassurance.
  tools     name -> {desc, args, label}; label is "risky"/"careful" or rule(args).
            Lesson from v1: optional args default to the safe value via .get();
            only arguments the decision depends on raise -> parse_fail.

Register style guide: human = lowercase, contractions, a typo, emotion, no polish;
ai = complete, formal, polished sentences. Propositional content is kept equal.
"""

